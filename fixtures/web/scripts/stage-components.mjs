import { cpSync, mkdirSync, rmSync } from "node:fs";
import { fileURLToPath } from "node:url";
const source = fileURLToPath(new URL("../../../components/web/", import.meta.url));
const target = fileURLToPath(new URL("../src/components/", import.meta.url));
const tokenSource = fileURLToPath(new URL("../../../design/tokens.css", import.meta.url));
const tokenTarget = fileURLToPath(new URL("../src/design/tokens.css", import.meta.url));
const designTarget = fileURLToPath(new URL("../src/design/", import.meta.url));
rmSync(target, { recursive: true, force: true });
mkdirSync(target, { recursive: true });
cpSync(source, target, { recursive: true });
rmSync(designTarget, { recursive: true, force: true });
mkdirSync(designTarget, { recursive: true });
cpSync(tokenSource, tokenTarget);
console.log("Staged local web components and semantic tokens for fixture compilation.");
